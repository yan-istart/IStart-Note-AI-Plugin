import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "module";
import { copyFileSync, mkdirSync, readFileSync } from "fs";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
/* Phosphor Icons 2.1.1: ${readFileSync("THIRD_PARTY_NOTICES.md", "utf8").split("MIT License")[1]} */
`;

const prod = process.argv[2] === "production";

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  inject: ["src/core/sync/browserBuffer.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    // Git's browser dependencies need the bundled Buffer polyfill on mobile.
    ...builtinModules.filter((name) => name !== "buffer"),
  ],
  format: "cjs",
  target: "es2018",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "dist/main.js",
});

if (prod) {
  await context.rebuild();
  mkdirSync("dist", { recursive: true });

  // Release assets must match the tagged source, including the manifest version.
  copyFileSync("manifest.json", "dist/manifest.json");
  copyFileSync("styles.css", "dist/styles.css");
  copyFileSync("THIRD_PARTY_NOTICES.md", "dist/THIRD_PARTY_NOTICES.md");

  console.log(`Build complete: ${JSON.parse(readFileSync("manifest.json", "utf8")).version}`);
  process.exit(0);
} else {
  await context.watch();
}
